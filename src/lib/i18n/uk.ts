/** Ukrainian plural: 1 файл, 2 файли, 5 файлів (11–14 always "many"). */
const pl = (n: number, one: string, few: string, many: string) => {
  const last = n % 10;
  const teens = n % 100 >= 11 && n % 100 <= 14;
  if (last === 1 && !teens) return one;
  if (last >= 2 && last <= 4 && !teens) return few;
  return many;
};

